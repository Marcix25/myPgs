#!/usr/bin/env node
//# BUILD STATIC DEMO
//+ demo/assets/demo.structure.html is a component, not a page — opening it directly shows an empty
//+ nav and an empty main. This script combines it with the rendered reference files into the three
//+ generated outputs, all living under demo/build/ (demo/ itself only holds DOCUMENTATION.md,
//+ assets/ and build/):
//+ - demo/assets/demo.structure.html — hand-authored page shell (head, header, page layout,
//+   footer), no content-loading script of its own. Edit this for structural/layout changes.
//+ - demo/build/demo.content.html — generated, reference-only: just the nav and every panel's
//+   markup, written out by demo/assets/demo-render.js (the same rendering demo-fetch.js does live
//+   in the browser), with no page shell around it. Not a page either — a component, same as
//+   demo.structure.html, just a generated one.
//+ - demo/build/demo-fetch.html — generated: demo.structure.html plus demo-fetch.js, so opening it
//+   fetches and renders every reference/html/*.html file live, same as demo.structure.html used to
//+   do standalone.
//+ - demo/build/demo.html — generated: demo.structure.html with demo.content.html's nav+panels
//+   spliced in, plus demo.js instead of demo-fetch.js. Opens instantly, no fetch, no per-file
//+   parsing — the one to use while iterating on assets/. Components built entirely by JS at runtime
//+   (notification, toast, modal, accordion, ...) are untouched either way: their source markup is
//+   baked in like everything else, and pgs.init() still builds them for real when the page loads.
//+
//+ Run with: npm run demo:build

"use strict";

const fs = require("fs");
const path = require("path");
const DemoRender = require("../demo/assets/demo-render.js");

const PROJECT_ROOT = path.resolve(__dirname, "..");
const REFERENCE_ROOT = path.join(PROJECT_ROOT, "reference", "html");
const STRUCTURE_HTML = path.join(PROJECT_ROOT, "demo", "assets", "demo.structure.html");
const BUILD_DIR = path.join(PROJECT_ROOT, "demo", "build");
const CONTENT_HTML = path.join(BUILD_DIR, "demo.content.html");
const FETCH_HTML = path.join(BUILD_DIR, "demo-fetch.html");
const OUTPUT_HTML = path.join(BUILD_DIR, "demo.html");
const COMPILED_CSS = path.join(PROJECT_ROOT, "dist", "css", "index.css");
const WELCOME_FILE = path.join(REFERENCE_ROOT, "guides", "welcome.html");

function readIfExists(file) {
    return fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
}

function buildNavAndPanels() {
    const cssText = readIfExists(COMPILED_CSS);
    const menuEntries = [];
    let panelsHtml = "";

    const welcomeSource = readIfExists(WELCOME_FILE);
    if (welcomeSource) {
        panelsHtml += `<div data-panel="${DemoRender.WELCOME_ENTRY.path}" hidden pgs="flexColumn" pgs-option="gapElements">${welcomeSource}</div>`;
        menuEntries.push(DemoRender.WELCOME_ENTRY);
    } else {
        console.warn(`[build-demo-static] welcome.html non trovato in ${path.relative(PROJECT_ROOT, WELCOME_FILE)}`);
    }

    DemoRender.referenceFiles.forEach(relativePath => {
        const file = path.join(REFERENCE_ROOT, relativePath);
        if (!fs.existsSync(file)) {
            console.warn(`[build-demo-static] riferimento mancante, saltato: ${relativePath}`);
            return;
        }

        const rawFileText = fs.readFileSync(file, "utf8");
        const { title, panelHtml } = DemoRender.renderReferencePanelHtml(relativePath, rawFileText, cssText);
        panelsHtml += panelHtml;
        menuEntries.push({ path: relativePath, title });
    });

    const navHtml = DemoRender.renderNavHtml(menuEntries, true);
    return { navHtml, panelsHtml, count: menuEntries.length };
}

//+ demo.content.html holds just the two generated fragments, each inside its own <template> so the
//+ file parses as valid (inert) HTML on its own — a <template>'s content never renders — while still
//+ being trivial for readContentFile below to tell apart
function writeContentFile(navHtml, panelsHtml) {
    const output = "<!-- Automatically generated by scripts/build-demo-static.js from reference/html/**/*.html. " +
        "Reference-only: no page shell. A component, not a page — merged into demo.structure.html to " +
        "produce demo.html. Do not edit, and do not open directly (a <template>'s content is inert " +
        "until parsed back out). -->\n" +
        `<template id="demo-content-nav">${navHtml}</template>\n` +
        `<template id="demo-content-main">${panelsHtml}</template>\n`;
    fs.writeFileSync(CONTENT_HTML, output);
}

function readContentFile() {
    const source = fs.readFileSync(CONTENT_HTML, "utf8");
    const extract = id => {
        const pattern = new RegExp(`<template id="${id}">([\\s\\S]*?)<\\/template>`);
        const match = source.match(pattern);
        if (!match) throw new Error(`<template id="${id}"> non trovato in build/demo.content.html`);
        return match[1];
    };
    return { navHtml: extract("demo-content-nav"), panelsHtml: extract("demo-content-main") };
}

function insertBeforeBodyClose(html, scriptsBlock) {
    if (!/<\/body>/.test(html)) throw new Error("nessun </body> trovato in assets/demo.structure.html");
    return html.replace(/<\/body>/, `    ${scriptsBlock}\n</body>`);
}

//+ Strips comments and collapses whitespace runs to a single space in the final generated pages —
//+ demo.html bakes in ~45 reference panels verbatim, indentation and all, so this trims real weight
//+ off the file. <script>/<pre>/<textarea> blocks are left untouched: example code and JSON payloads
//+ (both copied verbatim into "Example HTML"/"PGS Option fields" panels) depend on their exact
//+ whitespace. Collapsing to one space rather than removing it entirely avoids merging adjacent
//+ inline elements that relied on that space to stay visually separated.
function minifyHtml(html) {
    const protectedBlocks = [];
    let output = html.replace(/<(script|pre|textarea)\b[^>]*>[\s\S]*?<\/\1>/gi, match => {
        protectedBlocks.push(match);
        return `\u0000${protectedBlocks.length - 1}\u0000`;
    });

    output = output.replace(/<!--[\s\S]*?-->/g, "");
    output = output.replace(/\s+/g, " ").trim();

    return output.replace(/\u0000(\d+)\u0000/g, (match, index) => protectedBlocks[Number(index)]);
}

//+ demo-fetch.html: the shell as-is, plus the script that makes it fetch and render every
//+ reference/html/*.html file live — functionally identical to what demo.structure.html used to be
//+ when opened directly, before it became a component
function buildFetchHtml(shellHtml) {
    const output = insertBeforeBodyClose(shellHtml, `<script src="../assets/demo-fetch.js"></script>`);
    return `<!-- Automatically generated by scripts/build-demo-static.js from assets/demo.structure.html. Do not edit — run npm run demo:build again after changing it. -->\n${minifyHtml(output)}`;
}

//+ demo.html: the shell with demo.content.html's nav+panels spliced into the empty containers,
//+ plus demo.js instead of demo-fetch.js. demo-render.js is a build-time-only dependency (used by
//+ this script, in Node) — nothing in the browser reads it, so it has no reason to be on the page.
function buildFinalHtml(shellHtml, navHtml, panelsHtml) {
    let output = shellHtml;

    //== both the desktop aside and the mobile dialog copy share the same empty
    //== `class="reference-demo-nav"` wrapper — demo-fetch.js fills each one identically, so this does too
    const navWrapperPattern = /(<div\b[^>]*class="reference-demo-nav"[^>]*>)(\s*)(<\/div>)/g;
    let navMatches = 0;
    output = output.replace(navWrapperPattern, (match, openTag, _whitespace, closeTag) => {
        navMatches++;
        return `${openTag}${navHtml}${closeTag}`;
    });
    if (navMatches === 0) throw new Error('nessun elemento class="reference-demo-nav" trovato in assets/demo.structure.html');

    const mainPattern = /(<main\b[^>]*id="reference-demo-main"[^>]*>)(\s*)(<\/main>)/;
    if (!mainPattern.test(output)) throw new Error('nessun <main id="reference-demo-main"> trovato in assets/demo.structure.html');
    output = output.replace(mainPattern, (match, openTag, _whitespace, closeTag) => `${openTag}${panelsHtml}${closeTag}`);

    output = insertBeforeBodyClose(output, `<script src="../assets/demo.js"></script>`);

    return `<!-- Automatically generated by scripts/build-demo-static.js from assets/demo.structure.html + build/demo.content.html. Do not edit — run npm run demo:build again after changing either. -->\n${minifyHtml(output)}`;
}

function main() {
    const shellHtml = fs.readFileSync(STRUCTURE_HTML, "utf8");
    const { navHtml, panelsHtml, count } = buildNavAndPanels();

    fs.mkdirSync(BUILD_DIR, { recursive: true });

    writeContentFile(navHtml, panelsHtml);
    console.log(`[build-demo-static] ${path.relative(PROJECT_ROOT, CONTENT_HTML)} scritto con ${count} pannelli.`);

    fs.writeFileSync(FETCH_HTML, buildFetchHtml(shellHtml));
    console.log(`[build-demo-static] ${path.relative(PROJECT_ROOT, FETCH_HTML)} scritto (assets/demo.structure.html + assets/demo-fetch.js).`);

    const { navHtml: mergedNav, panelsHtml: mergedPanels } = readContentFile();
    fs.writeFileSync(OUTPUT_HTML, buildFinalHtml(shellHtml, mergedNav, mergedPanels));
    console.log(`[build-demo-static] ${path.relative(PROJECT_ROOT, OUTPUT_HTML)} scritto (assets/demo.structure.html + build/demo.content.html).`);
}

main();
